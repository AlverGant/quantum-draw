/**
 * Escolhe o idioma: ?lang= na URL, depois a escolha salva, depois o navegador.
 *
 * O parâmetro vem primeiro porque é o que o sitemap e as tags hreflang
 * apontam — se ele não mandasse, o Google veria a mesma página em inglês nas
 * oito URLs e trataria como conteúdo duplicado.
 */
export function detectLocale() {
  // Páginas estáticas por idioma (/pt/, /es/, …) injetam isto no HTML. Vem
  // antes de tudo: quem chega em /pt/ pelo Google tem que ver português já no
  // primeiro quadro, mesmo nunca tendo visitado o site.
  const fromPage = typeof window !== 'undefined' ? window.__QDRAW_LANG__ : null;
  if (fromPage && STRINGS[fromPage]) {
    localStorage.setItem('qdraw.lang', fromPage);
    return fromPage;
  }

  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (fromUrl && STRINGS[fromUrl]) return fromUrl;

  const saved = localStorage.getItem('qdraw.lang');
  if (saved && STRINGS[saved]) return saved;
  for (const tag of navigator.languages ?? [navigator.language ?? '']) {
    const short = String(tag).toLowerCase().split('-')[0];
    if (STRINGS[short]) return short;
  }
  return DEFAULT_LOCALE;
}
